export async function saveProtectionAction(
  _prevState: PatrimonioActionState,
  formData: FormData
): Promise<PatrimonioActionState> {
  const session = await requirePatrimonioSession();

  const parsed = patrimonioProtectionSchema.safeParse({
    id: f(formData, "id"),
    element: f(formData, "element"),
    objective: f(formData, "objective"),
    currentValueCents: f(formData, "currentValueCents"),
    idealValueCents: f(formData, "idealValueCents"),
    isNeeded: f(formData, "isNeeded"),
    isCovered: f(formData, "isCovered"),
    notes: f(formData, "notes"),
  });
  if (!parsed.success) {
    return { error: "Verifique os campos informados.", fieldErrors: parsed.error.flatten().fieldErrors };
  }

  const document = await extractOptionalDocument(formData);
  if (document.present && "error" in document) {
    return { error: document.error, fieldErrors: { document: [document.error] } };
  }
  const documentData = documentPatch(document, f(formData, "removeDocument") === "true");

  const { id, ...data } = parsed.data;

  if (id) {
    const existing = await prisma.patrimonioProtection.findUnique({ where: { id } });
    if (!existing || existing.userId !== session.userId) {
      return { error: "Item não encontrado." };
    }
    await prisma.patrimonioProtection.update({ where: { id }, data: { ...data, ...documentData } });
  } else {
    const maxOrder = await prisma.patrimonioProtection.aggregate({
      where: { userId: session.userId },
      _max: { order: true },
    });
    await prisma.patrimonioProtection.create({
      data: { ...data, ...documentData, userId: session.userId, order: (maxOrder._max.order ?? 0) + 1 },
    });
  }

  revalidatePath("/patrimonio");
  return { success: true };
}

/** Proteção never accumulates the kind of value-history this module
 * tracks for ativos/passivos (its "Valor da Proteção Atual" isn't
 * logged the same way), so unlike deleteAssetAction/deleteLiabilityAction
 * there's no history to protect — always a soft-delete, matching the
 * isActive convention every list/total here already filters on. */
export async function deleteProtectionAction(formData: FormData) {
  const session = await requirePatrimonioSession();
  const parsed = patrimonioDeleteSchema.safeParse({ id: f(formData, "id") });
  if (!parsed.success) throw new Error("Item inválido.");

  await prisma.patrimonioProtection.updateMany({
    where: { id: parsed.data.id, userId: session.userId },
    data: { isActive: false },
  });
  revalidatePath("/patrimonio");
}

/** Necessidade/Coberto's toggle switches (ProtectionTable.tsx) flip
 * straight from the table, no "Editar e atualizar" needed first — same
 * immediacy as the "Pago" toggle in Lançamentos
 * (markTransactionPaidStatusAction), so this takes a plain typed object
 * rather than FormData like every save/delete action above (there's no
 * <form> involved, the toggle calls this directly). */
export async function setProtectionFlagAction(input: {
  id: string;
  field: "isNeeded" | "isCovered";
  value: boolean;
}) {
  const session = await requirePatrimonioSession();
  const { id, field, value } = input;

  await prisma.patrimonioProtection.updateMany({
    where: { id, userId: session.userId },
    data: field === "isNeeded" ? { isNeeded: value } : { isCovered: value },
  });
  revalidatePath("/patrimonio");
}

/** "Fotografia do mês" — confirms/adjusts one bem ou dívida's value for
 * one specific month (src/lib/patrimonio.ts's sparse confirmation
 * ledger). Upsert: re-confirming the same item+month just updates the
 * value instead of erroring on the unique constraint. Deliberately
 * separate from PatrimonioValueChange (the "Editar e atualizar" history
 * above) — this is the existing monthly-projection mechanic and is left
 * untouched. */
export async function confirmMonthlyValueAction(
  _prevState: PatrimonioActionState,
  formData: FormData
): Promise<PatrimonioActionState> {
  const session = await requirePatrimonioSession();

  const parsed = patrimonioConfirmMonthlyValueSchema.safeParse({
    kind: f(formData, "kind"),
    itemId: f(formData, "itemId"),
    monthKey: f(formData, "monthKey"),
    valueCents: f(formData, "valueCents") ?? "",
  });
  if (!parsed.success) {
    return { error: "Verifique os campos informados.", fieldErrors: parsed.error.flatten().fieldErrors };
  }
  const { kind, itemId, monthKey, valueCents } = parsed.data;

  if (kind === "asset") {
    const asset = await prisma.patrimonioAsset.findUnique({ where: { id: itemId } });
    if (!asset || asset.userId !== session.userId) return { error: "Item não encontrado." };
    await prisma.patrimonioMonthlyConfirmation.upsert({
      where: { assetId_monthKey: { assetId: itemId, monthKey } },
      update: { valueCents },
      create: { userId: session.userId, assetId: itemId, monthKey, valueCents },
    });
  } else {
    const liability = await prisma.patrimonioLiability.findUnique({ where: { id: itemId } });
    if (!liability || liability.userId !== session.userId) return { error: "Item não encontrado." };
    await prisma.patrimonioMonthlyConfirmation.upsert({
      where: { liabilityId_monthKey: { liabilityId: itemId, monthKey } },
      update: { valueCents },
      create: { userId: session.userId, liabilityId: itemId, monthKey, valueCents },
    });
  }

  revalidatePath("/patrimonio");
  return { success: true };
}
